const assert=require('node:assert/strict');
const {fitsA4,labelPages}=require('../../resources/js/scripts/pages/procurement-labels.js');
const sheet={columns:2,rows:5,width:104.9867,height:56.9912,gap_x:0,gap_y:0,margin_x:0.0133,margin_y:6.014,offset_x:0,offset_y:0};
assert.equal(fitsA4(sheet),true);
assert.equal(fitsA4({...sheet,width:105}),false);
assert.equal(fitsA4({...sheet,height:59}),false);
assert.equal(fitsA4({...sheet,offset_x:-2}),false);
assert.equal(fitsA4({...sheet,columns:2.5}),false);
const labels=Array.from({length:23},(_,id)=>({id}));
const pages=labelPages(labels,10);
assert.deepEqual(pages.map(page=>page.length),[10,10,3]);
assert.deepEqual(pages.flat(),labels);
assert.deepEqual(labelPages([],10),[]);
assert.throws(()=>labelPages(labels,0));
console.log('Two-column A4 labels and multi-page ordering passed.');
